-- ОНООГ НЭГ ОРОНГООР УРТ БОЛГОНО (×10).
--
-- Хичээл дуусгахад «+10 оноо» гэж гарах нь хэт жижиг мэдрэгддэг байв.
--
-- ⚠ ТЭНЦВЭР ӨӨРЧЛӨГДӨХГҮЙ: шагнал (`lessons.xp_reward`), түвшний босго
-- (`lib/tactiq/xp.ts`), амжилтын шат (`sage`), найзын долоо хоногийн
-- зорилт бүгд НЭГЭН ЗЭРЭГ ×10 болов. Зөвхөн шагналыг өсгөвөл сурагч хоёр
-- хичээлээр 3-р түвшинд хүрч, түвшин утгаа алдана.
--
-- ⚠ ХУУЧИН ӨГӨГДЛИЙГ ЗААВАЛ ЗЭРЭГ ӨСГӨНӨ. Эс тэгвэл өмнөх сурагчид
-- шинэ босгоор хэдэн түвшин ДООШ унана — тоглоомжуулалтад хамгийн
-- ноцтой алдаа нь аль хэдийн авсан зүйлийг буцаан авах.

-- 1. Хичээлийн шагнал.
UPDATE lessons SET xp_reward = xp_reward * 10;
ALTER TABLE lessons ALTER COLUMN xp_reward SET DEFAULT 100;

-- 2. Сурагчийн нийт оноо (түвшин эндээс тооцогддог).
UPDATE users SET xp = xp * 10 WHERE xp > 0;

-- 3. Хичээл бүрийн олгосон онооны хуулбар — түүх, тайланд хэрэглэгдэнэ.
UPDATE lesson_progress SET xp_earned = xp_earned * 10 WHERE xp_earned > 0;

-- 4. Энэ долоо хоногийн лигийн оноо.
--
-- ⚠ Бүх гишүүнийг ижил коэффициентээр өсгөж байгаа тул ЭРЭМБЭ хэвээр —
-- явж байгаа тэмцээн гажихгүй.
UPDATE league_members SET xp = xp * 10 WHERE xp > 0;

-- 5. Найзын зорилт — зорилго ба хоёр талын хувь нэмэр ХАМТ.
--
-- ⚠ Зөвхөн зорилгыг өсгөвөл яг дуусах гэж байсан хос эхнээсээ эхэлнэ.
UPDATE friend_quests
SET goal_xp = goal_xp * 10,
    xp_a = xp_a * 10,
    xp_b = xp_b * 10;
