-- УРАМШУУЛЛЫН КОДЫН ШАТАЛСАН ХУВЬ.
--
-- «Эхний 50 хүүхэд 50%, дараагийн 75 хүүхэд 25%» гэсэн нөхцөлийг
-- хадгална. Бүтэц (`PromoTier[]`):
--
--   [{ "limit": 50, "discountPercent": 50, "commissionPercent": 10 },
--    { "limit": 75, "discountPercent": 25, "commissionPercent": 10 }]
--
-- ⚠ `limit` нь ТУХАЙН ШАТНЫ ХЭМЖЭЭ, нийлбэр БИШ: «эхний 50, дараагийн
-- 75» гэж уншина (нийт 125). Нийлбэрээр бичвэл админ хоёр дахь шатыг
-- 125 гэж тоолох шаардлагатай болж, тоолохдоо ямагт эндүүрнэ.
--
-- ⚠ ШАТ ДУУСВАЛ кодын ҮНДСЭН хувь (`discount_percent`,
-- `commission_percent`) хэрэгжинэ. Тиймээс шатгүй код нь урьдын адил
-- ажиллана — хуучин кодуудад миграц шаардлагагүй.
--
-- ⚠ ТООЛОЛТ нь ТӨЛӨГДСӨН (`payments.status = 'paid'`) бөгөөд ӨӨР ӨӨР
-- худалдан авагчаар: нэг хүүхэд хоёр багц авбал «хоёр хүүхэд» гэж
-- тоологдох ёсгүй. Тоог ХАДГАЛАХГҮЙ, ямагт төлбөрийн мөрүүдээс тооцно —
-- хадгалсан тоолуур нь төлбөр цуцлагдах, буцаах үед ҮРГЭЛЖ зөрдөг.

ALTER TABLE promo_codes ADD COLUMN IF NOT EXISTS tiers jsonb;

-- Тоололтын асуулга: `promo_code` + `status` хоёроор шүүж, `uid`-аар
-- distinct тоолно.
CREATE INDEX IF NOT EXISTS payments_promo_paid_idx
  ON payments (promo_code, status)
  WHERE promo_code IS NOT NULL;
