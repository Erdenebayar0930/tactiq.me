-- ТЕСТЕР ЭРХ — бүх хичээл нээлттэй сурагч.
--
-- ⚠ ЯАГААД ЭРХ (`role`) БИШ, ТУГ ВЭ: тестер нь ЯМАГТ СУРАГЧ хэвээр —
-- түүний зам, оноо, лиг, чансаа бүгд сурагчийнх шиг ажиллана. `role`-д
-- шинэ утга нэмбэл «хэн хэнийг удирдах» шатлал (`lib/permissions.ts`-ийн
-- `roleRank`, `canActOn`) бүхэлдээ хөндөгдөж, багш/эцэг эхийн хамаарал
-- дээр санамсаргүй цоорхой үүсэх эрсдэлтэй.
--
-- ⚠ ЗӨВХӨН АДМИН олгоно (`/api/users/[uid]`). Хэрэглэгч өөрөө тохируулж
-- чадвал төлбөртэй агуулга бүхэлдээ нээлттэй болно.
--
-- ⚠ Анхдагч `false`: туг нь ОНЦГОЙ тохиолдол (туршилт, багшийн
-- үзүүлбэр) бөгөөд «бүгд тестер» болох нь хичээлийн дараалал гэсэн
-- сурах зарчмыг үгүй болгоно.

ALTER TABLE users ADD COLUMN IF NOT EXISTS tester boolean NOT NULL DEFAULT false;

-- Админы жагсаалтад «тестерүүд» гэж шүүх боломжтой байхад хэрэгтэй.
CREATE INDEX IF NOT EXISTS users_tester_idx ON users (tester) WHERE tester;
