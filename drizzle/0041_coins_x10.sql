-- ЗООСЫГ НЭГ ОРОНГООР УРТ БОЛГОНО (×10).
--
-- ⚠ ТЭНЦВЭР ӨӨРЧЛӨГДӨХГҮЙ: шагнал (хичээл 5→50, хайрцаг 15→150) ба үнэ
-- (дэлгүүр, тэжээвэр амьтан, цувааны хамгаалалт) хоёуланг НЭГЭН ЗЭРЭГ
-- ×10 болгов. Зөвхөн нэгийг нь өсгөвөл дэлгүүр 10 дахин хямд болно.
--
-- ⚠ ХУУЧИН ҮЛДЭГДЛИЙГ ЗААВАЛ ЗЭРЭГ ӨСГӨНӨ. Эс тэгвэл өмнө нь 400 зоос
-- цуглуулсан сурагч шинэ үнээр (4000) юу ч авч чадахгүй болж, зоос нь
-- хулгайлагдсан мэт мэдрэгдэнэ.
UPDATE users SET gems = gems * 10 WHERE gems > 0;

-- ⚠ `path_chests.gems` нь ТҮҮХЭН бичлэг (аль хайрцгаас хэдийг авсан) —
-- үлдэгдэлд дахин нөлөөлөхгүй тул ХӨНДӨХГҮЙ.

-- Шинээр бүртгүүлэгчийн эхлэлийн бэлэг (230 → 2300).
ALTER TABLE users ALTER COLUMN gems SET DEFAULT 2300;
