--
-- Урьд нь аль хэдийн дуусгасан хичээлийг дахин хийхэд оноо ОГТ
-- олгогддоггүй байв (`lesson_progress_uid_lesson_uq`-ийн зөрчил дээр
-- `xpEarned: 0` буцаана). Давталт нь суралцах үнэ цэнэтэй тул одооноос
-- анхны дүнгийн 20%-ийг олгоно (`lib/tactiq/rewards.ts`).
--
-- ⚠ ХОЁР ХАМГААЛАЛТ «ТАРИАЛАН»-ГИЙН ЭСРЭГ:
--   1. хувь нь бага (20%);
--   2. хичээл тус бүрд ӨДӨРТ ГАНЦ удаа — `last_repeat_day`.
-- Аль нэг нь дутвал хамгийн амархан хичээлээ дахин дахин дарж лигийн
-- тэргүүнд гарах зам нээгдэнэ.
--
-- ⚠ `last_repeat_day` нь NULL байж БОЛНО: хуучин мөрүүд давталтын оноо
-- хэзээ ч аваагүй тул анхны давталтдаа шууд эрхтэй. Өдрийн хэлбэр нь
-- `YYYY-MM-DD` (`lib/tactiq/day.ts`-ийн `today()`) — цагийн бүстэй
-- `timestamp` биш, учир нь «өдөр» гэдгийг платформ даяар НЭГ мужаар
-- (Улаанбаатар) тоолдог.

ALTER TABLE lesson_progress
  ADD COLUMN IF NOT EXISTS repeat_count integer NOT NULL DEFAULT 0;

ALTER TABLE lesson_progress
  ADD COLUMN IF NOT EXISTS last_repeat_day varchar(10);
