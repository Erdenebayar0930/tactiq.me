/**
 * ШАТРЫН НЭР ТОМЪЁО — ЭЦСИЙН хэлбэрт хөрвүүлнэ: «ШАГ» ба «МАД».
 *
 * ⚠ ЭЗНИЙ ЭЦСИЙН ШИЙДВЭР (2026-09-18): шад → ШАГ, маг → МАД. Өмнө нь
 * би эсрэгээр (шаг → шад, мад → маг) буруу хөрвүүлсэн — энэ скрипт нь
 * түүнийг буцаах ба хуучин «шат / мат» үлдэгдлийг ч эцсийн хэлбэрт
 * оруулна. Тиймээс хэдэн ч удаа ажиллуулж болно (идемпотент): гарц нь
 * ямагт «шаг / мад».
 *
 * ⚠ ХӨНДӨЖ БОЛОХГҮЙ ҮГС: «шагнал», «шагай», «шаглах», «магадлал»,
 * «магадгүй», «шатлах», «шатлал». Тиймээс зөвхөн БҮТЭН ҮГИЙН хэлбэрийг
 * тоочиж, кирилл үсгээр хүрээлээгүй эсэхийг lookaround-аар шалгана.
 *
 * ⚠ `\b` ХЭРЭГЛЭХГҮЙ: JS-ийн `\b` нь ASCII-д тулгуурладаг тул кирилл
 * үсгийн хажууд хүрээ ОЛОХГҮЙ — `/\bшад\b/` нь монгол бичвэрт ХЭЗЭЭ Ч
 * таарахгүй. Энэ нь эхний оролдлогод бодитоор тохиолдсон бөгөөд доорх
 * хамгаалалтын туршилт л түүнийг барьсан.
 *
 * ⚠ ТИЙН ЯЛГАЛ: «шаг» нь -г-ээр төгсдөг тул «цаг» шиг (шагт, шагаас,
 * шагийг, шаггүй), «мад» нь -д-гээр төгсдөг тул «хад» шиг (мадыг,
 * мадын). Шууд залгавал монгол хэлэнд байхгүй хэлбэр гарна.
 *
 * Ажиллуулах:  node scripts/_chess_terms.mjs [--apply]
 */
import fs from "node:fs";
import pg from "pg";

const url = (fs.readFileSync(".env.local", "utf8").match(/^DATABASE_URL=(.*)$/m) || [])[1].trim();

const MN = "А-Яа-яӨөҮүЁё";
const word = (mn) => new RegExp(`(?<![${MN}])${mn}(?![${MN}])`, "g");

/**
 * Хувиргалтууд — УРТААС БОГИНО руу.
 *
 * ⚠ Дараалал чухал: «шад»-ыг эхэлж тавибал «шадаас» нь хагас хувирна.
 */
const RULES = [
  // --- ШАД → ШАГ (тийн ялгал нь «цаг» шиг) ---
  [word("шадаас"), "шагаас"],
  [word("Шадаас"), "Шагаас"],
  [word("ШАДААС"), "ШАГААС"],
  [word("шадыг"), "шагийг"],
  [word("Шадыг"), "Шагийг"],
  [word("ШАДЫГ"), "ШАГИЙГ"],
  [word("шадгүй"), "шаггүй"],
  [word("Шадгүй"), "Шаггүй"],
  [word("шадад"), "шагт"],
  [word("Шадад"), "Шагт"],
  [word("ШАДАД"), "ШАГТ"],
  [word("шад"), "шаг"],
  [word("Шад"), "Шаг"],
  [word("ШАД"), "ШАГ"],

  // Хуучин «шат» хэлбэрүүд (шатрын утгаар) — ТОМ үсгээр л таардаг.
  [word("ШАТАНД"), "ШАГТ"],
  [word("ШАТААС"), "ШАГААС"],
  [word("ШАТ"), "ШАГ"],

  // --- МАГ → МАД (тийн ялгал нь «хад» шиг) ---
  [word("магийг"), "мадыг"],
  [word("Магийг"), "Мадыг"],
  [word("МАГИЙГ"), "МАДЫГ"],
  [word("магийн"), "мадын"],
  [word("Магийн"), "Мадын"],
  [word("магаас"), "мадаас"],
  [word("магад"), "мадад"],
  [word("маг"), "мад"],
  [word("Маг"), "Мад"],
  [word("МАГ"), "МАД"],
  [word("МАТ"), "МАД"],
];

export function fixTerms(text) {
  let out = String(text);
  for (const [pattern, replacement] of RULES) out = out.replace(pattern, replacement);
  return out;
}

/* --- ХАМГААЛАЛТЫН ТУРШИЛТ --- */
const GUARD = [
  // Хөндөгдөх ЁСГҮЙ үгс
  ["Шагналын сан 500,000₮", "Шагналын сан 500,000₮"],
  ["шагнал, шагай, шаглах", "шагнал, шагай, шаглах"],
  ["магадлал, магадгүй", "магадлал, магадгүй"],
  ["Анхан шат, Дунд шат", "Анхан шат, Дунд шат"],
  ["хүндрэлийг шатлан нэмнэ", "хүндрэлийг шатлан нэмнэ"],
  // Буцаах хувиргалт
  ["Цагаан ноён шадад байна!", "Цагаан ноён шагт байна!"],
  ["Шадаас гарах гурван арга", "Шагаас гарах гурван арга"],
  ["шадыг хаа", "шагийг хаа"],
  ["Шад байвал МАГ (хожил), шадгүй бол ПАТ", "Шаг байвал МАД (хожил), шаггүй бол ПАТ"],
  ["магийг ол", "мадыг ол"],
  ["2 нүүдэлд магийн бодлого", "2 нүүдэлд мадын бодлого"],
  ["Маг! Та яллаа!", "Мад! Та яллаа!"],
  ["хар ноён ШАДАД байх ёстой", "хар ноён ШАГТ байх ёстой"],
  ["Хар ноёнд ШАД өг", "Хар ноёнд ШАГ өг"],
  // Идемпотент: аль хэдийн зөв бичвэр ХЭВЭЭР
  ["Шаг! Ноёноо нүүлгэ. Мад биш.", "Шаг! Ноёноо нүүлгэ. Мад биш."],
];

let failed = 0;
for (const [input, expected] of GUARD) {
  const actual = fixTerms(input);
  if (actual !== expected) {
    failed++;
    console.error(`  ✗ "${input}"\n     хүлээсэн: "${expected}"\n     гарсан:   "${actual}"`);
  }
}
if (failed) {
  console.error(`ХАМГААЛАЛТЫН ТУРШИЛТ ${failed} газар бүтэлгүйтэв — санд юу ч бичихгүй.`);
  process.exit(1);
}
console.log(`хамгаалалтын туршилт: ${GUARD.length}/${GUARD.length} ✓`);

/* --- САНГИЙН БИЧИЛТ --- */
const COLUMNS = [
  ["courses", "slug", ["title", "description"]],
  ["units", "id", ["title"]],
  ["lessons", "id", ["title"]],
  ["exercises", "id", ["prompt", "explanation"]],
];

const apply = process.argv.includes("--apply");
const client = new pg.Client({ connectionString: url });
await client.connect();

let changed = 0;
for (const [table, key, cols] of COLUMNS) {
  const rows = (await client.query(`select ${key}, ${cols.join(", ")} from ${table}`)).rows;

  for (const row of rows) {
    const patch = {};
    for (const col of cols) {
      const before = row[col];
      if (!before) continue;
      const after = fixTerms(before);
      if (after !== before) patch[col] = after;
    }
    if (Object.keys(patch).length === 0) continue;

    changed++;
    if (apply) {
      const sets = Object.keys(patch).map((col, i) => `${col} = $${i + 2}`);
      await client.query(`update ${table} set ${sets.join(", ")} where ${key} = $1`, [
        row[key],
        ...Object.values(patch),
      ]);
    }
  }
}

console.log(`${changed} мөр${apply ? " → БИЧСЭН" : " (туршилт)"}`);
await client.end();
