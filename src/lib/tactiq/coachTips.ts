import type { Chess } from "chess.js";
import type { Draughts } from "@/lib/draughts/engine";

/**
 * ДАСГАЛЖУУЛАГЧИЙН ДҮРМИЙН ТАЙЛБАР — хөлөг дээр БОДИТООР тохиолдсон
 * мөчид тохирох нэг өгүүлбэр.
 *
 * ЯАГААД ТУСДАА ФАЙЛ, ЯАГААД ЦЭВЭР ФУНКЦ ВЭ:
 *   • Нэг дүрмийг хоёр дэлгэцэд (ботын тоглолт, хичээл) өөр өөр үгээр
 *     тайлбарлавал хүүхэд хоёр өөр дүрэм сурсан гэж бодно. Бичвэр НЭГ
 *     ГАЗАР байх нь тайлбаруудыг нэг дуу хоолойтой байлгана.
 *   • `Chess`/`Draughts`-ыг л хүлээж авдаг цэвэр функц тул React-гүйгээр
 *     шалгаж, дуудаж болно.
 *
 * ⚠ ТАЙЛБАР НЭГ УДАА: дуудагч тал аль тайлбарыг аль хэдийн харуулсныг
 * санаж, давтахгүй байх ёстой (`CoachTip`-ийн `shownRef` загвар). «Мад»
 * гэдгийг нүүдэл бүрд дахин дахин хэлэх нь зөвлөгөө биш, чимээ шуугиан.
 */
export type CoachTip = {
  /** Давхардлыг хянах түлхүүр — дуудагч тал үүнийг санана. */
  id: string;
  /**
   * Эрэмбэ — нэг мөчид хэд хэдэн дүрэм тохирвол ИХ тоо нь дээгүүр гарна.
   * Жишээ нь «боож байна» гэдэг нь «төв нүдийг эзэл» гэсэн ерөнхий
   * зөвлөгөөнөөс ЯМАГТ чухал: сурагч эхлээд хаанаа аврах ёстой.
   */
  priority: number;
  text: string;
};

const tip = (id: string, priority: number, text: string): CoachTip => ({ id, priority, text });

/**
 * ШАТРЫН дүрмийн тайлбар — тоглогч (цагаан) нүүх ээлжтэй мөчид дуудагдана.
 *
 * Жагсаалт нь ДАРААЛЛААРАА биш, `priority`-гаар эрэмбэлэгдэнэ.
 */
export function chessTips(chess: Chess): CoachTip[] {
  const tips: CoachTip[] = [];
  const history = chess.history();
  const moves = chess.moves({ verbose: true });

  if (history.length === 0) {
    tips.push(
      tip(
        "chess:goal",
        10,
        "Шатрын зорилго нь өрсөлдөгчийн ноёныг МАД хийх — зугтах газаргүй болтол боох."
      )
    );
    tips.push(
      tip(
        "chess:center",
        5,
        "Эхлэлд төв нүдийг (d4, e4, d5, e5) эзлэхийг хичээ. Төвөөс дүрс бүр илүү олон нүд хамгаална."
      )
    );
  }

  if (chess.inCheck()) {
    tips.push(
      tip(
        "chess:check",
        100,
        "Ноён чинь БООЛТ дор байна. Гурван л зам бий: ноёныг зөөх, боож байгаа дүрсийг идэх, эсвэл хооронд дүрс тавих."
      )
    );
  }

  // Хувиргалт: хүү сүүлийн эгнээнд хүрэх нүүдэл байна уу.
  if (moves.some((move) => move.promotion)) {
    tips.push(
      tip(
        "chess:promotion",
        60,
        "Хүү чинь 8-р эгнээнд хүрэх гэж байна! Тэнд хүрмэгц бэрс, тэрэг, тэмээ, морь — аль ч дүрс болж хувирна."
      )
    );
  }

  if (moves.some((move) => move.isKingsideCastle() || move.isQueensideCastle())) {
    tips.push(
      tip(
        "chess:castle",
        40,
        "Одоо БҮТЭЭХ (сэлгээ) боломжтой: ноён хоёр нүд хөдөлж, тэрэг түүний хажууд бууна. Ноёноо хамгаалах хамгийн хурдан арга."
      )
    );
  }

  if (moves.some((move) => move.isEnPassant())) {
    tips.push(
      tip(
        "chess:en-passant",
        50,
        "«Зугтсан хүү» (en passant): хоёр нүд үсэрсэн хүүг яг тэр дор нэг нүд үсэрсэн мэт идэж болно."
      )
    );
  }

  return tips.sort((a, b) => b.priority - a.priority);
}

/**
 * ДААМЫН дүрмийн тайлбар.
 *
 * ⚠ Даамын ХАМГИЙН ТӨӨРӨГДҮҮЛДЭГ хоёр дүрэм нь «идэлт заавал» ба
 * «хамгийн урт цувааг сонгох» — сурагч идэхгүй нүүх гэж оролдоод хөлөг
 * зөвшөөрөхгүй үед шалтгааныг мэдэхгүй бол аппыг эвдэрсэн гэж бодно.
 * Тиймээс тэр хоёрыг идэлт БОЛОМЖТОЙ яг тэр мөчид тайлбарлана.
 */
export function draughtsTips(game: Draughts): CoachTip[] {
  const tips: CoachTip[] = [];
  const moves = game.legalMoves();
  const capture = moves.find((move) => move.captures.length > 0);
  const history = game.moveHistory();
  const board = game.board();

  /*
   * Хөлгийн ТООЛЛОГО — зөвлөгөө нь байрлалаас хамаарах ёстой.
   *
   * ⚠ Нэг удаа тоолж хуваалцана: тайлбар бүрд дахин гүйлгэвэл нүүдэл
   * бүрд хөлгийг олон дахин алхана.
   */
  let myMen = 0;
  let myKings = 0;
  let theirMen = 0;
  let theirKings = 0;
  let myBackRow = 0;
  let myEdge = 0;

  for (let row = 0; row < board.length; row += 1) {
    for (let col = 0; col < board[row].length; col += 1) {
      const piece = board[row][col];
      if (!piece) continue;

      if (piece.color === "w") {
        if (piece.king) myKings += 1;
        else myMen += 1;
        // Цагаан доод эгнээнээс эхэлдэг тул түүний «ар тал» нь сүүлийн мөр.
        if (row === board.length - 1) myBackRow += 1;
        if (col === 0 || col === board[row].length - 1) myEdge += 1;
      } else if (piece.king) theirKings += 1;
      else theirMen += 1;
    }
  }

  const mine = myMen + myKings;
  const theirs = theirMen + theirKings;

  // --- Дүрэм: эхлэхэд нэг удаа ------------------------------------------
  if (history.length === 0) {
    tips.push(
      tip(
        "draughts:goal",
        10,
        "Даамын зорилго нь өрсөлдөгчийн бүх дүрсийг идэх явдал."
      )
    );
  }

  // --- Дүрэм: идэлт -----------------------------------------------------
  if (capture) {
    tips.push(
      tip(
        "draughts:must-capture",
        100,
        "Идэх боломж гарвал ЗААВАЛ идэх ёстой — даамд «идэхгүй өнгөрөх» гэж үгүй."
      )
    );

    if (moves.length === 1) {
      tips.push(
        tip(
          "draughts:longest",
          90,
          "Хэд хэдэн идэлт байвал ХАМГИЙН УРТ цувааг сонгох ёстой. Тиймээс заримдаа ганцхан нүүдэл хууль ёсны болдог."
        )
      );
    }

    if (capture.captures.length > 1) {
      tips.push(
        tip(
          "draughts:chain",
          80,
          "Нэг нүүдэлд хэд хэдэн дүрс идэж болно: идсэн газраа зогсохгүй, цааш идэх боломж байвал үргэлжлүүлэн үсэрнэ."
        )
      );
    }

    if (capture.captures.length >= 3) {
      tips.push(
        tip(
          "draughts:big-chain",
          95,
          "Гурав ба түүнээс олон дүрс идэх цуваа бол даамын хамгийн хүчтэй зэвсэг. Идэхийнхээ өмнө цувааныхаа ТӨГСГӨЛД хаана зогсохоо хараарай."
        )
      );
    }
  } else if (history.length > 2) {
    /*
     * ⚠ Идэлтгүй мөчид л ерөнхий зөвлөгөө өгнө. Идэлт байхад сурагчийн
     * бүх анхаарал тэр дээр байх ёстой — өөр зөвлөгөө нь саад л болно.
     */
    tips.push(
      tip(
        "draughts:tempo",
        20,
        "Идэлт байхгүй бол дүрсээ урагш, хамтдаа нүүлгэ: ганцаарчилсан дүрс амархан баригддаг."
      )
    );
  }

  // --- Даам -------------------------------------------------------------
  if (moves.some((move) => move.promoted)) {
    tips.push(
      tip(
        "draughts:king",
        70,
        "Сүүлийн эгнээнд хүрсэн хүү ДАМКА болно: даам урагш, хойш аль ч чигт, хэдэн ч нүд хөдөлнө."
      )
    );
  }

  if (myKings > 0) {
    tips.push(
      tip(
        "draughts:king-power",
        40,
        "Даам нь хол зайнаас идэж чадна — түүнийг урт диагональ дээр тавь, тэндээс хөлгийн хоёр талыг зэрэг заналхийлнэ."
      )
    );
  }

  if (theirKings > myKings) {
    tips.push(
      tip(
        "draughts:their-king",
        60,
        "Өрсөлдөгч даамтай боллоо. Даамын замыг хаах нь түүнийг идэхээс хамаагүй амархан: диагональ дээр нь өөрийн хоёр дүрсийг зэрэгцүүлж тавь."
      )
    );
  }

  // --- Ар тал, зах ------------------------------------------------------
  if (history.length > 6 && myBackRow >= 3) {
    tips.push(
      tip(
        "draughts:back-row",
        35,
        "Ар талын эгнээгээ хэт удаан бүтэн барих хэрэггүй — тэнд зогссон дүрс тоглоомд оролцдоггүй. Хоёр, гурвыг нь үлдээгээд бусдыг урагшлуул."
      )
    );
  }

  if (myEdge >= 3) {
    tips.push(
      tip(
        "draughts:edge",
        30,
        "Захын нүдэн дээрх дүрсийг ИДЭЖ БОЛОХГҮЙ — тэр нь давуу тал мэт боловч зөвхөн нэг чиглэлд нүүдэг тул хүч нь хагасаар буурна."
      )
    );
  }

  // --- Материалын байдал ------------------------------------------------
  if (history.length > 10 && mine > theirs) {
    tips.push(
      tip(
        "draughts:trade-ahead",
        45,
        "Чи дүрсээр илүү байна. Ийм үед СОЛИЛЦОХ нь ашигтай: дүрс цөөрөх тусам илүү дүрсний давуу тал нь томордог."
      )
    );
  }

  if (history.length > 10 && theirs > mine) {
    tips.push(
      tip(
        "draughts:behind",
        45,
        "Дүрсээр хоцорч байна. Солилцохоос зайлсхийж, дүрсээ ойр байлга — хамтдаа зогссон дүрсийг идэх нь хэцүү."
      )
    );
  }

  if (mine <= 4 && myKings === 0) {
    tips.push(
      tip(
        "draughts:endgame",
        50,
        "Дүрс цөөрлөө. Одоо хамгийн чухал зорилго нь нэг дүрсээ ДАМКА болгох — нэг даам гурван хүүтэй тэнцэнэ."
      )
    );
  }

  // --- Хавчаа -----------------------------------------------------------
  if (moves.length === 1 && !capture) {
    tips.push(
      tip(
        "draughts:only-move",
        85,
        "Ганцхан нүүдэл үлдлээ. Нүүх боломж бүрмөсөн дуусвал тоглоом ялагдлаар төгсдөг — дүрсээ хэт бөөгнүүлэхээс сэрэмжил."
      )
    );
  }

  return tips.sort((a, b) => b.priority - a.priority);
}
