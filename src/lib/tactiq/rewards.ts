/**
 * Хичээлийн шагналын тогтмолууд — клиент, сервер хоёулаа импортолно.
 *
 * ⚠ НЭГ Л ГАЗАР. Хичээл дуусгах route (`api/learn/lessons/[lessonId]/complete`)
 * энэ тоогоор зоос олгодог бөгөөд `/courses` дэлгэцийн «зоос» үзүүлэлт ч
 * эндээс тооцогдоно — хоёр газарт бичвэл нэгийг нь өөрчлөхөд карт худал
 * тоо харуулна.
 */

/** Хичээл дуусгахад олгох зоос — XP (`lessons.xp_reward`) хичээл бүрт өөр ч энэ нь тогтмол. */
export const LESSON_GEM_REWARD = 50;

/**
 * ДАВТАН ҮЗЭХЭД олгох онооны ХУВЬ (анхны дүнгээс).
 *
 * ⚠ ЯАГААД БАГА ВЭ: давталт нь СУРАЛЦАХ үнэ цэнэтэй тул огт шагналгүй
 * байх нь хүүхдийг дахин хийхээс няцаана. Гэхдээ бүтэн оноо өгвөл
 * хамгийн амархан хичээлээ дахин дахин хийж лигийн тэргүүнд гарах зам
 * нээгдэнэ — суралцахгүйгээр оноо цуглуулна.
 *
 * ⚠ ӨДӨРТ НЭГ УДАА: түүнээс гадна давталтын оноо нь хичээл тус бүрд
 * ӨДӨРТ ГАНЦ удаа олгогдоно (`lesson_progress.last_repeat_day`). Хоёр
 * хамгаалалт хамтдаа «тариалан»-г боломжгүй болгоно.
 */
export const REPEAT_XP_PERCENT = 20;

/**
 * Давтан үзэхэд олгох оноо.
 *
 * ⚠ ДООД ТАЛДАА 1: бага онооны хичээл (5 XP) дээр 20% нь 1-ээс бага
 * гарч, бүхэлчлэхэд 0 болно. «Оноо аваад 0 нэмэгдэв» гэдэг нь алдаа мэт
 * харагдана.
 */
export const repeatXp = (xpReward: number): number =>
  xpReward > 0 ? Math.max(1, Math.round((xpReward * REPEAT_XP_PERCENT) / 100)) : 0;
