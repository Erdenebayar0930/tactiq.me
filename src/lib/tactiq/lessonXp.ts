/**
 * ХИЧЭЭЛИЙН ОНООГ АГУУЛГААС нь ТООЦНО.
 *
 * ⚠ Урьд нь оноо нь ГАРААР бичигдэж байсан: seed скрипт бүр өөрийн
 * дуртай тоог өгдөг байв. Үр дүнд нь 12 дасгалтай шатрын хичээл ч, нэг
 * товшилтоор дуусах таавар ч ойролцоо оноотой болж, сурагч «бага
 * ажилтай» хичээлүүдийг түүж хийх нь ашигтай болж байлаа.
 *
 * ⚠ `server-only` БИШ: админы дэлгэц шинэ хичээл үүсгэхдээ санал болгох
 * оноог ЭНДЭЭС тооцно — сервер тал ижил функцээр бичнэ.
 *
 * ФОРМУЛ: Σ(дасгалын жин) × хүндрэлийн коэффициент, 10-д бөөрөнхийлнө.
 */

/**
 * Дасгалын НЭГЖ ЖИН — «дунджаар хэдэн секунд бодох вэ» гэдгээс гаралтай,
 * зөв хариултын тоо ЭСВЭЛ сонголтын тооноос БИШ.
 *
 * ⚠ Шинэ төрөл нэмэхэд ЭНД бичихээ бүү мартаарай: `DEFAULT_WEIGHT` нь
 * зөвхөн осол даах зориулалттай бөгөөд дунджаар буруу байна.
 */
export const EXERCISE_XP: Record<string, number> = {
  // Нэг товшилт — уншаад хариулна.
  choice: 20,
  series: 25,
  word: 30,
  recall: 60,

  // Хөлөг дээрх НЭГ нүүдэл — дүрмээ мэдэж байвал шууд.
  "board-move": 25,
  "draughts-move": 25,

  // Тактик: хэд хэдэн хувилбар тооцох шаардлагатай.
  "chess-puzzle": 40,
  "draughts-puzzle": 40,
  "memory-game": 60,
  matchstick: 50,

  // Бүтэн самбар дүүргэнэ — хэдэн минутын ажил.
  sudoku: 80,
  tangram: 80,
  nonogram: 100,
  "slide-puzzle": 100,
};

const DEFAULT_WEIGHT = 30;

/**
 * Хичээлийн НЭРНЭЭС хүндрэлийг таана.
 *
 * ⚠ Хүндрэл нь тусдаа БАГАНА БИШ, нэрэнд байдаг («4×4 хүнд 3»,
 * «хөнгөн 12»). Багана нэмэх нь цэвэрхэн ч 700 гаруй мөрийг гараар
 * ангилах шаардлагатай болно — нэр нь seed скриптүүдэд аль хэдийн
 * тогтсон, найдвартай дохио.
 */
export function difficultyFactor(title: string, positionRatio?: number): number {
  const lower = title.toLowerCase();
  if (lower.includes("хүнд") || lower.includes("хэцүү")) return 1.5;
  if (lower.includes("хөнгөн") || lower.includes("амархан")) return 0.8;

  /*
   * ⚠ НЭРЭНД ХҮНДРЭЛ БАЙХГҮЙ бол БАЙРЛАЛААР. Бүлгүүд нь бараг үргэлж
   * хөнгөнөөс хүнд рүү эрэмбэлэгдсэн байдаг («Хос олох 1…9» — сүүлийнх нь
   * хамгийн олон хөзөртэй). Байрлалыг тооцохгүй бол бүлэг доторх бүх
   * хичээл ИЖИЛ оноотой болж, ахиц мэдрэгдэхээ болино.
   */
  if (positionRatio === undefined) return 1;
  if (positionRatio >= 2 / 3) return 1.2;
  if (positionRatio >= 1 / 3) return 1;
  return 0.8;
}

/** Хамгийн бага оноо — хоосон/танигдаагүй хичээл ч 0 болохгүй. */
const MIN_XP = 50;

/**
 * @param exerciseTypes Хичээл доторх дасгалуудын төрөл, ДАРААЛЛААР.
 * @param title Хичээлийн нэр — хүндрэлийг эхлээд эндээс хайна.
 * @param positionRatio Бүлэг доторх байрлал (0 = эхний, 1 = сүүлийн).
 *   Нэрэнд хүндрэл байхгүй үед л хэрэглэгдэнэ.
 */
export function lessonXpReward(
  exerciseTypes: string[],
  title = "",
  positionRatio?: number
): number {
  const base = exerciseTypes.reduce(
    (sum, type) => sum + (EXERCISE_XP[type] ?? DEFAULT_WEIGHT),
    0
  );

  const scaled = base * difficultyFactor(title, positionRatio);

  // ⚠ 10-д бөөрөнхийлнө: «+237 оноо» гэдэг нь тохируулсан юм шиг биш,
  // алдаа гарсан юм шиг харагддаг.
  return Math.max(MIN_XP, Math.round(scaled / 10) * 10);
}
