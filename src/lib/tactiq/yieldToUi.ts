/**
 * Удирдлагыг хөтчид буцааж, дараагийн тактад үргэлжлүүлнэ.
 *
 * ⚠ Урт минимакс хайлт нь ЦОРЫН ГАНЦ JS урсгалыг эзэлдэг: шинжилгээ явж
 * байхад товч дарагдахгүй, анимаци зогсож, гар утсан дээр апп "унасан" мэт
 * харагдана. Давталт тутамд энэ функцийг `await` хийвэл хөтөч завсарт
 * дэлгэцээ зурж, оролтыг боловсруулж амждаг.
 *
 * `setTimeout(0)` нь `queueMicrotask`-аас ЯЛГААТАЙ: микротаск нь мөн адил
 * урсгалыг сулладаггүй тул зурагдалт хойшлогдсоор байна. Макротаск л
 * жинхэнэ завсар үүсгэнэ.
 */
export function yieldToUi(): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, 0));
}
