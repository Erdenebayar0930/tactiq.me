import { translate, type Locale } from "./dictionary";

/**
 * `t("Монгол бичвэр")` — бүх компонентод ижилхэн хэрэглэгдэх хөрвүүлэгч.
 *
 * ЯАГААД HOOK БИШ, МОДУЛИЙН ФУНКЦ ВЭ:
 * Аппад 750+ бичвэр 84 файлд тархсан бөгөөд файл бүрд хэд хэдэн компонент,
 * мөн компонентоос ГАДНА (`function endMessage(...)`, тогтмол хүснэгт) байдаг
 * бичвэр бий. Hook нь компонентын ДОТОР л дуудагдах тул тэдгээрийг бүгдийг
 * дахин бүтэцлэх шаардлагатай болно — бодит ажлын 10 дахин нь орчуулгад биш,
 * дамжуулалтад зарцуулагдана.
 *
 * ⚠ Модулийн төлөв React-ийн рендэрийн системээс ГАДНА байдаг тул хэл
 * солиход компонент өөрөө дахин зурагдахгүй. Үүнийг `LocaleProvider` нь
 * бүх модыг `key={locale}`-ээр ДАХИН МОНТЛОХ замаар шийднэ: хэл солих нь
 * ховор, зориудын үйлдэл тул бүтэн дахин монтлолт нь хамгийн найдвартай
 * (хагас орчуулагдсан дэлгэц гарах боломжгүй).
 */
let currentLocale: Locale = "mn";

export const setActiveLocale = (locale: Locale) => {
  currentLocale = locale;
};

export const activeLocale = () => currentLocale;

export const t = (text: string) => translate(currentLocale, text);
