/**
 * Найзын урилгын код — сервер, клиент ХОЁУЛАА хэрэглэдэг тул `server-only`
 * БИШ. Клиент тал зөвхөн `inviteUrl`-ыг ашиглана.
 */

/**
 * Тодорхойгүй үсэг (0/O, 1/I) хассан цагаан толгой — код нь заримдаа
 * холбоосоор БИШ, амаар/зурвасаар дамждаг (`schema.ts`-ийн эцэг эхийн
 * урилгатай ижил шалтгаан).
 */
const ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";

/** 8 тэмдэгт = 32⁸ ≈ 1.1 их наяд хувилбар — таах замаар олох боломжгүй. */
export const newInviteCode = () =>
  Array.from(
    { length: 8 },
    () => ALPHABET[Math.floor(Math.random() * ALPHABET.length)]
  ).join("");

/**
 * Холбоос амьдрах хугацаа. Урьсан хүн дэлгэцээ нээгээд хүлээж байдаг тул
 * УРТ байх нь утгагүй — 30 минутын дараа ирсэн найз "хүлээж байна" гэсэн
 * хэн ч байхгүй өрөөнд ганцаараа үлдэнэ.
 */
export const INVITE_TTL_MS = 30 * 60 * 1000;

/** Найзад илгээх бүтэн холбоос — зөвхөн хөтөч дээр дуудагдана. */
export const inviteUrl = (code: string) =>
  `${window.location.origin}/play/invite/${code}`;
