/**
 * Node.js процессын түвшний хамгаалалт.
 *
 * ЯАГААД ТУСДАА ФАЙЛ ВЭ: `instrumentation.ts` нь Node БОЛОН Edge хоёуланд
 * зориулж баглагддаг. `process.on` дуудлагыг тэр файлд шууд бичвэл ажиллах
 * үедээ хамгаалалттай байсан ч (`NEXT_RUNTIME` шалгалт) бандлагч түүнийг
 * Edge бандлаас олж, компиляц бүрд "A Node.js API is used" гэсэн
 * анхааруулга өгнө. Динамик импортоор тусгаарлавал Edge бандлад энэ код
 * ОГТ ОРОХГҮЙ тул анхааруулга үндсээрээ арилна.
 *
 * ЮУ ХИЙДЭГ ВЭ: Node 20-д баригдаагүй Promise-ийн алдаа нь процессыг ШУУД
 * УНАГААНА (`--unhandled-rejections=throw` нь анхдагч). Тэр үед апп
 * бүхэлдээ унаж, прокси нь 502 өгнө. Route бүрийн `try/catch` нь дуусаагүй
 * фон ажлыг (жишээ нь `void backfillClaimsIfStale(...)`) хамгаалж чадахгүй.
 *
 * ⚠ `uncaughtException`-ыг залгих нь эрсдэлтэй гэж үздэг — процессын төлөв
 * гэмтсэн байж болно. Гэвч shared hosting дээр процессыг Passenger л
 * сэргээдэг бөгөөд тэр нь дараагийн хүсэлт ирэх хүртэл хийгддэггүй. Тиймээс
 * "унасан ч чимээгүй" байхаас "амьд бөгөөд логтой" нь энэ орчинд илүү
 * найдвартай. Санах ой гэмтэх төрлийн алдаанд `max_memory_restart`-ын
 * үүргийг Passenger өөрөө гүйцэтгэнэ.
 */
export function registerProcessHandlers() {
  process.on("unhandledRejection", (reason) => {
    console.error("[process] баригдаагүй Promise алдаа:", reason);
  });

  process.on("uncaughtException", (error) => {
    console.error("[process] баригдаагүй алдаа:", error);
  });

  /**
   * Гарах шалтгааныг тэмдэглэнэ — Passenger процессыг дахин асаахад логт
   * "яагаад" гэдэг нь үлдэнэ. Үүнгүйгээр restart нь ул мөргүй болно.
   */
  process.on("SIGTERM", () => {
    console.log("[process] SIGTERM — зогсож байна");
  });
}
